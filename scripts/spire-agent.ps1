#Requires -Version 5.1
<#
.SYNOPSIS
    Starts the SPIRE Agent for local development.

.DESCRIPTION
    Runs SPIRE Agent as a foreground process.
    Data is stored under $DataDir.
    Press Ctrl+C to stop.

.PARAMETER SpireAgentBin
    Path to the spire-agent executable. Defaults to "spire-agent" (must be on PATH).

.PARAMETER DataDir
    Directory where SPIRE Agent stores its key and state. Defaults to ".\data\spire-agent".

.PARAMETER ConfigPath
    Path to the SPIRE Agent config file. Defaults to ".\configs\spire-agent.conf".

.PARAMETER JoinToken
    Optional join token generated by SPIRE Server to bootstrap the agent's identity.

.PARAMETER LogLevel
    Log level (debug | info | warn | error). Defaults to "info".

.EXAMPLE
    .\spire-agent.ps1 -JoinToken "a1b2c3d4-..."
#>
[CmdletBinding()]
param(
    [string] $SpireAgentBin = "spire-agent",
    [string] $DataDir       = ".\data\spire-agent",
    [string] $ConfigPath    = ".\configs\spire-agent.conf",
    [string] $JoinToken     = "",
    [string] $LogLevel      = "info"
)

Set-StrictMode -Version Latest
$ErrorActionPreference = "Stop"

# ---------------------------------------------------------------------------
# Resolve paths relative to Project Root
# ---------------------------------------------------------------------------
$ProjectRoot = Split-Path -Parent $PSScriptRoot
$OldDir = Get-Location
Set-Location $ProjectRoot

try {
    $ResolvedDataDir = $ExecutionContext.SessionState.Path.GetUnresolvedProviderPathFromPSPath($DataDir)
    $ResolvedConfig = $ExecutionContext.SessionState.Path.GetUnresolvedProviderPathFromPSPath($ConfigPath)

    # If a Join Token is provided, remove stale keys/bundle so agent performs fresh attestation
    if ($JoinToken -and (Test-Path $ResolvedDataDir)) {
        Write-Host "Join token provided. Cleaning stale agent data in $ResolvedDataDir..." -ForegroundColor Yellow
        Remove-Item "$ResolvedDataDir\*" -Recurse -Force -ErrorAction SilentlyContinue
    }

    # Ensure data directory exists
    if (-not (Test-Path $ResolvedDataDir)) {
        New-Item -ItemType Directory -Path $ResolvedDataDir -Force | Out-Null
    }

    # Verify binary is available
    if (-not (Get-Command $SpireAgentBin -ErrorAction SilentlyContinue)) {
        Write-Error "spire-agent binary '$SpireAgentBin' not found. Install SPIRE and add it to PATH, or pass -SpireAgentBin <path>."
        exit 1
    }

    # Print effective config
    Write-Host ""
    Write-Host "=== SPIRE AGENT ======================================================" -ForegroundColor Cyan
    Write-Host "  Executable  : $SpireAgentBin"
    Write-Host "  Config Path : $ResolvedConfig"
    Write-Host "  Data Dir    : $ResolvedDataDir"
    Write-Host "  Join Token  : $(if ($JoinToken) { $JoinToken } else { '[None - using stored key]' })"
    Write-Host "  Log Level   : $LogLevel"
    Write-Host "======================================================================" -ForegroundColor Cyan
    Write-Host ""

    # Build agent arguments
    $agentArgs = @(
        "run",
        "-config", $ResolvedConfig,
        "-logLevel", $LogLevel
    )
    if ($JoinToken) {
        $agentArgs += @("-joinToken", $JoinToken)
    }

    # Start SPIRE Agent
    Write-Host "Starting SPIRE Agent (foreground)...  Press Ctrl+C to stop." -ForegroundColor Yellow
    & $SpireAgentBin @agentArgs
}
finally {
    Set-Location $OldDir
}
